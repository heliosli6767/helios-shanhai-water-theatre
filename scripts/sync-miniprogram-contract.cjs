'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const contracts = ['home', 'story'];
let stale = false;

for (const name of contracts) {
  // Mechanical package build: a native mini program cannot require outside its root.
  const source = fs.readFileSync(path.join(root, 'packages/api-contracts/' + name + '.js'), 'utf8');
  const target = path.join(root, 'apps/wechat-miniprogram/services/' + name + '-contract.js');
  const content = '// Generated by npm run sync:miniprogram. Edit packages/api-contracts/' + name + '.js instead.\n' + source;
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      console.error('小程序契约未同步：' + name);
      stale = true;
    }
  } else {
    fs.writeFileSync(target, content);
    console.log('小程序 API 契约已同步：' + name);
  }
}

if (stale) process.exitCode = 1;
