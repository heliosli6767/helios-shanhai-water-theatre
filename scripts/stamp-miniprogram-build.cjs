'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

function stamp() {
  const root = path.resolve(__dirname, '../apps/wechat-miniprogram');
  const hash = crypto.createHash('sha256');
  function visit(directory) {
    for (const name of fs.readdirSync(directory).sort()) {
      const filename = path.join(directory, name);
      if (fs.statSync(filename).isDirectory()) visit(filename);
      else if (/\.(js|json|wxml|wxss)$/.test(name) && name !== 'build-info.js' && !name.startsWith('project.')) {
        hash.update(path.relative(root, filename));
        hash.update(fs.readFileSync(filename));
      }
    }
  }
  visit(root);
  const revision = hash.digest('hex').slice(0, 8);
  const info = { id: `VK-${revision}`, revision, builtAt: new Date().toISOString() };
  fs.writeFileSync(path.join(root, 'shared/build-info.js'), "'use strict';\n// Generated by scripts/stamp-miniprogram-build.cjs\nmodule.exports = " + JSON.stringify(info, null, 2) + ';\n');
  console.log(`小程序版本标记：${info.id}`);
  return info;
}

module.exports = stamp;
if (require.main === module) stamp();
